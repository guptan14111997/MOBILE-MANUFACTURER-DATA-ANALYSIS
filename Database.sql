/************************************************************************************************
Create tables in the database as per schema
************************************************************************************************/
CREATE TABLE DIM_MANUFACTURER (
    IDManufacturer INT PRIMARY KEY AUTO_INCREMENT,
    Manufacturer_Name VARCHAR(20)
);
ALTER TABLE DIM_MANUFACTURER AUTO_INCREMENT = 11;

CREATE TABLE DIM_MODEL (
    IDModel INT PRIMARY KEY AUTO_INCREMENT,
    Model_Name VARCHAR(20),
    Unit_price DECIMAL(10, 2),
    IDManufacturer INT,
    FOREIGN KEY (IDManufacturer) REFERENCES DIM_MANUFACTURER(IDManufacturer)
);
ALTER TABLE DIM_MODEL AUTO_INCREMENT = 101;

CREATE TABLE DIM_CUSTOMER (
    IDCustomer INT PRIMARY KEY AUTO_INCREMENT,
    Customer_Name VARCHAR(30),
    Email VARCHAR(40),
    Phone BIGINT
);
ALTER TABLE DIM_CUSTOMER AUTO_INCREMENT = 10001;

CREATE TABLE DIM_LOCATION (
    IDLocation INT PRIMARY KEY AUTO_INCREMENT,
    ZipCode INT,
    Country VARCHAR(20),
    `State` VARCHAR(20),
    City VARCHAR(20)
);
ALTER TABLE DIM_LOCATION AUTO_INCREMENT = 2001;

CREATE TABLE DIM_DATE (
    DTE DATE PRIMARY KEY,
    YR INT GENERATED ALWAYS AS (YEAR(DTE)) STORED,
    QTR INT GENERATED ALWAYS AS (QUARTER(DTE)) STORED,
    MNTH INT GENERATED ALWAYS AS (MONTH(DTE)) STORED
);

CREATE TABLE FACT_TRANSACTIONS (
    IDModel INT,
    IDCustomer INT,
    IDLocation INT,
    DTE DATE,
    TotalPrice DECIMAL(10, 2),
    Quantity INT,
    FOREIGN KEY (IDModel) REFERENCES DIM_MODEL(IDModel),
    FOREIGN KEY (IDCustomer) REFERENCES DIM_CUSTOMER(IDCustomer),
    FOREIGN KEY (IDLocation) REFERENCES DIM_LOCATION(IDLocation),
    FOREIGN KEY (`DTE`) REFERENCES DIM_DATE(`DTE`)
);

